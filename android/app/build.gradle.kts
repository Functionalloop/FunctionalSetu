fun props(file: String): Properties = Properties().apply {
    val f = rootProject.file(file)
    if (f.exists()) f.inputStream().use { load(it) }
}

val local = props("local.properties")
val keystore = props("keystore.properties")

// local.properties wins over gradle.properties, so each laptop can point the debug app at its own LAN address.
fun setting(name: String): String =
    local.getProperty(name) ?: (findProperty(name) as String?) ?: error("$name is not set")

